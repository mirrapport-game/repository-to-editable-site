export const questionById = (id: string) => clubQuestions.find((q) => q.id === id);

/** Один случайный вопрос на каждом этапе: знакомство, первое свидание, начали встречаться. */
export function pickInviteQuestions(): ClubQuestion[] {
  return (["meet", "date", "dating"] as const).map((stage) => {
    const list = clubQuestions.filter((q) => q.stage === stage);
    return list[Math.floor(Math.random() * list.length)]!;
  });
}

